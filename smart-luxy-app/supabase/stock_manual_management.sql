-- Gestion manuelle du stock Wazyo
-- Les modifications sont atomiques, protégées par is_admin() et historisées.

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  variant_type text not null check (variant_type in ('product', 'model', 'color')),
  variant_name text,
  movement_type text not null check (movement_type in ('entry', 'exit', 'adjustment')),
  quantity integer not null check (quantity >= 0),
  stock_before integer not null check (stock_before >= 0),
  stock_after integer not null check (stock_after >= 0),
  reason text not null check (length(trim(reason)) >= 3),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.stock_movements enable row level security;

drop policy if exists "Admins read stock movements" on public.stock_movements;
create policy "Admins read stock movements"
  on public.stock_movements for select to authenticated
  using (public.is_admin());

drop policy if exists "Admins insert stock movements" on public.stock_movements;
create policy "Admins insert stock movements"
  on public.stock_movements for insert to authenticated
  with check (public.is_admin());

revoke all on public.stock_movements from anon;\ngrant select, insert on public.stock_movements to authenticated;
grant usage, select on sequence public.stock_movements_id_seq to authenticated;

create or replace function public.admin_adjust_product_stock(
  p_product_id bigint,
  p_variant_type text,
  p_variant_name text,
  p_operation text,
  p_quantity integer,
  p_reason text
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
declare
  v_product public.products%rowtype;
  v_items jsonb;
  v_updated_items jsonb := '[]'::jsonb;
  v_item jsonb;
  v_current integer;
  v_new integer;
  v_match_count integer := 0;
  v_movement_type text;
  v_variant_label text;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Accès refusé : administrateur requis';
  end if;

  if p_variant_type is null or p_variant_type not in ('product', 'model', 'color') then
    raise exception 'Type de stock invalide';
  end if;

  if p_operation is null or p_operation not in ('add', 'remove', 'set') then
    raise exception 'Opération de stock invalide';
  end if;

  if p_quantity is null
     or p_quantity < 0
     or (p_operation in ('add', 'remove') and p_quantity = 0) then
    raise exception 'Quantité invalide';
  end if;

  if length(trim(coalesce(p_reason, ''))) < 3 then
    raise exception 'Le motif doit contenir au moins 3 caractères';
  end if;

  if p_variant_type in ('model', 'color') and length(trim(coalesce(p_variant_name, ''))) = 0 then
    raise exception 'Nom de variante manquant';
  end if;

  -- Verrouille la ligne produit : les ventes en ligne et les mouvements
  -- manuels ne peuvent pas se remplacer silencieusement.
  select * into v_product
  from public.products
  where id = p_product_id
  for update;

  if not found then
    raise exception 'Produit introuvable';
  end if;

  if p_variant_type = 'product' then
    v_current := greatest(coalesce(v_product.stock, 0), 0);

    if p_operation = 'add' then
      v_new := v_current + p_quantity;
      v_movement_type := 'entry';
    elsif p_operation = 'remove' then
      if p_quantity > v_current then
        raise exception 'Stock insuffisant : seulement % unité(s) disponible(s)', v_current;
      end if;
      v_new := v_current - p_quantity;
      v_movement_type := 'exit';
    else
      v_new := p_quantity;
      v_movement_type := 'adjustment';
    end if;

    update public.products set stock = v_new where id = p_product_id;
    v_variant_label := 'Stock général';

  else
    if p_variant_type = 'model' then
      if not coalesce(v_product.show_models, false) then
        raise exception 'La gestion des modèles est désactivée pour ce produit';
      end if;
      v_items := coalesce(v_product.models, '[]'::jsonb);
    else
      v_items := coalesce(v_product.colors, '[]'::jsonb);
    end if;

    if jsonb_typeof(v_items) <> 'array' then
      raise exception 'Structure des variantes invalide';
    end if;

    for v_item in select value from jsonb_array_elements(v_items)
    loop
      if v_item->>'name' = p_variant_name then
        v_match_count := v_match_count + 1;
        v_current := greatest(coalesce(nullif(v_item->>'stock', '')::integer, 0), 0);

        if p_operation = 'add' then
          v_new := v_current + p_quantity;
        elsif p_operation = 'remove' then
          if p_quantity > v_current then
            raise exception 'Stock insuffisant pour % : seulement % unité(s) disponible(s)', p_variant_name, v_current;
          end if;
          v_new := v_current - p_quantity;
        else
          v_new := p_quantity;
        end if;

        v_item := jsonb_set(v_item, '{stock}', to_jsonb(v_new), true);
      end if;

      v_updated_items := v_updated_items || jsonb_build_array(v_item);
    end loop;

    if v_match_count <> 1 then
      raise exception 'Variante introuvable ou nom non unique : %', p_variant_name;
    end if;

    if p_operation = 'add' then
      v_movement_type := 'entry';
    elsif p_operation = 'remove' then
      v_movement_type := 'exit';
    else
      v_movement_type := 'adjustment';
    end if;

    if p_variant_type = 'model' then
      update public.products set models = v_updated_items where id = p_product_id;
    else
      update public.products set colors = v_updated_items where id = p_product_id;
    end if;
    v_variant_label := p_variant_name;
  end if;

  insert into public.stock_movements (
    product_id, product_name, variant_type, variant_name,
    movement_type, quantity, stock_before, stock_after, reason, created_by
  ) values (
    v_product.id,
    v_product.nom,
    p_variant_type,
    v_variant_label,
    v_movement_type,
    abs(v_new - v_current),
    v_current,
    v_new,
    trim(p_reason),
    auth.uid()
  );

  return jsonb_build_object(
    'product_id', v_product.id,
    'product_name', v_product.nom,
    'variant_type', p_variant_type,
    'variant_name', v_variant_label,
    'movement_type', v_movement_type,
    'quantity', abs(v_new - v_current),
    'stock_before', v_current,
    'stock_after', v_new
  );
end;
$function$;

revoke all on function public.admin_adjust_product_stock(bigint, text, text, text, integer, text) from public;
grant execute on function public.admin_adjust_product_stock(bigint, text, text, text, integer, text) to authenticated;
